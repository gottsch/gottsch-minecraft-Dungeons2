def self_test() -> int:
    """Check the model against the worked examples in the Processor Manual, section 1.

    The manual is where these numbers were reasoned out and argued over; if the simulator disagrees
    with it, one of the two is wrong and it needs saying out loud rather than shipping a workbook
    that quietly contradicts the document authors are told to read.
    """
    failures = []

    def check(label, got, want, tolerance=5e-5):
        if abs(got - want) > tolerance:
            failures.append(f"{label}: got {got:.6f}, manual says {want:.6f}")

    # "Down a chain" -- the cobblestone table.
    chain = {"processor_type": "dungeons2:aging", "agings": 99, "rules": [
        {"block": "cobblestone", "output_blocks": [
            {"block": "mossy_cobblestone", "probability": 0.30},
            {"block": "rubble", "probability": 0.25},
            {"block": "dirt", "probability": 0.25}]}]}
    row = transition(chain)["cobblestone"]
    check("chain mossy", row["mossy_cobblestone"], 0.225)
    check("chain rubble", row["rubble"], 0.05625)
    check("chain dirt", row["dirt"], 0.01875)
    check("chain untouched", row["cobblestone"], 0.70)

    # `agings` truncates: the manual's silent-truncation trap, capped to two stages.
    capped = transition(dict(chain, agings=2))["cobblestone"]
    check("capped rubble", capped["rubble"], 0.075)
    check("capped dirt", capped.get("dirt", 0.0), 0.0)

    # "Across a fork" -- 30% / 30% is authored 0.30 then 0.43.
    fork = {"processor_type": "dungeons2:aging", "rules": [
        {"block": "b", "output_blocks": [{"block": "one", "probability": 0.30}]},
        {"block": "b", "output_blocks": [{"block": "two", "probability": 0.43}]}]}
    row = transition(fork)["b"]
    check("fork rule 1", row["one"], 0.30)
    check("fork rule 2", row["two"], 0.301, 0.002)

    # "To build a real multi-stage chain out of vanilla rules, give each stage its own entry":
    # three entries at 0.3 put 2.7% of the original block at the end.
    def rule_entry(source, target, probability):
        return {"processor_type": "minecraft:rule", "rules": [
            {"input_predicate": {"predicate_type": "minecraft:random_block_match",
                                 "block": source, "probability": probability},
             "output_state": {"Name": target}}]}

    entries = [rule_entry("minecraft:stone", "minecraft:cobblestone", 0.3),
               rule_entry("minecraft:cobblestone", "minecraft:gravel", 0.3),
               rule_entry("minecraft:gravel", "minecraft:air", 0.3)]
    ends = pipeline(entries)["minecraft:stone"]
    check("three entries end to end", ends["minecraft:air"][0], 0.027)
    check("and its own entry claims nothing", ends["minecraft:air"][1], 0.0)

    # Cross-contamination: the last entry catches gravel that was gravel all along, so seeding
    # gravel gives the authored 30% while seeding stone gives 2.7%. Same rule, two answers.
    check("a source already at the outcome's input",
          pipeline(entries)["minecraft:gravel"]["minecraft:air"][0], 0.3)

    for failure in failures:
        print("FAIL " + failure, file=sys.stderr)
    print(f"self-test: {'FAILED' if failures else 'ok'}"
          f" ({len(failures)} disagreements with the Processor Manual)")
    return 1 if failures else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="*", type=Path)
    parser.add_argument("-o", "--out", type=Path)
    parser.add_argument("--self-test", action="store_true",
                        help="check the model against the Processor Manual's worked examples")
    args = parser.parse_args()

    if args.self_test:
        return self_test()
    if not args.files or not args.out:
        parser.error("files and -o/--out are required unless --self-test is given")

    workbook = Workbook()
    workbook.remove(workbook.active)
    findings = []

    for path in args.files:
        data = json.loads(strip_comments(path.read_text(encoding="utf-8")))
        short = path.stem.replace("classic_", "").replace("_weathering", "")
        counter = 0
        for processor in data["processors"]:
            if not processor.get("rules"):
                continue
            counter += 1
            kind = processor["processor_type"].split(":")[-1].replace("_", " ")
            sheet_for(workbook, f"{short} {counter} {kind}", processor, path.name)

        # The pipeline, once per file: it is the whole list, not one entry of it.
        entries = [p for p in data["processors"] if p.get("rules")]
        if entries:
            found = pipeline_sheet(workbook, f"{short} PIPELINE", entries, path.name)
            findings += [(path.name,) + f for f in found]

    notes_sheet(workbook, [str(f) for f in args.files])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    workbook.save(args.out)
    print(f"wrote {args.out} ({len(workbook.sheetnames)} sheets)")

    # Print them too. The finding is the point of the sheet, and it should not need Excel to see.
    if findings:
        print(f"\n{len(findings)} rate(s) the per-entry sheets understate:")
        for name, source, outcome, end_to_end, own, note in findings:
            print(f"  {name}: {source} -> {outcome}"
                  f"  end-to-end {end_to_end:6.2%}  its own entry {own:6.2%}   {note}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
